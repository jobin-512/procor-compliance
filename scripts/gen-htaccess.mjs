// Generates public/.htaccess before every build. Adds a 301 for each migrated insight
// (content/insights/*.md with a body + legacyUrl) from its old /blogs/ URL to /insights/<slug>/.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(process.cwd(), 'content', 'insights');
const posts = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => {
  const raw = fs.readFileSync(path.join(dir, f), 'utf8');
  const [, fm = '', body = ''] = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/) || [];
  const get = (k) => (fm.match(new RegExp(`^${k}:\\s*(.*)$`, 'm')) || [])[1]?.trim().replace(/^["']|["']$/g, '') || '';
  return { slug: get('slug') || f.replace(/\.md$/, ''), legacy: get('legacyUrl'), migrated: body.trim().length > 0 };
});
const blogRules = posts.filter((p) => p.migrated && p.legacy)
  .map((p) => `RewriteRule ^${p.legacy.replace(/^\//, '').replace(/[.]/g, '\\.')}/?$ /insights/${p.slug}/ [R=301,L]`).join('\n');
const pending = posts.filter((p) => !p.migrated && p.legacy).map((p) => `#   ${p.legacy}`).join('\n');

const tpl = `# GENERATED by scripts/gen-htaccess.mjs — edit the script, not this file.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

RewriteEngine On
# 1) Canonical host: https://procor.co.in (no www)
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^ https://procor.co.in%{REQUEST_URI} [R=301,L]

# 2) Legacy .php URLs -> new clean URLs
RewriteRule ^index\\.php$                          /                                            [R=301,L]
RewriteRule ^about\\.php$                          /about/                                      [R=301,L]
RewriteRule ^services\\.php$                       /services/                                   [R=301,L]
RewriteRule ^payroll-processing\\.php$             /services/payroll-processing/                [R=301,L]
RewriteRule ^payroll-related-compliances\\.php$    /services/payroll-compliance/                [R=301,L]
RewriteRule ^hr-operations\\.php$                  /services/hr-operations/                     [R=301,L]
RewriteRule ^labour-law-compliances\\.php$         /services/labour-law-compliance/             [R=301,L]
RewriteRule ^finance-accounting-outsourcing\\.php$ /services/finance-accounting-outsourcing/    [R=301,L]
RewriteRule ^corporate-taxation-advisory\\.php$    /services/corporate-tax-regulatory-advisory/ [R=301,L]
RewriteRule ^blogs\\.php$                          /insights/                                   [R=301,L]
RewriteRule ^contact\\.php$                        /contact/                                    [R=301,L]
RewriteRule ^privacy-policy\\.php$                 /privacy-policy/                             [R=301,L]
# Short link for sharing: procor.co.in/hrms -> Procor HRMS (302 so it can change later)
RewriteRule ^hrms/?$ https://www.procorhrms.com/?utm_source=procor.co.in&utm_medium=referral&utm_campaign=procor_compliance&utm_content=short_link [R=302,L,NE]
RewriteRule ^industries/?$                        /who-we-help/                                [R=301,L]
RewriteRule ^services/payroll-compliances/?$      /services/payroll-compliance/                [R=301,L]

# 3) Migrated blog articles: /blogs/<slug> -> /insights/<slug>/
${blogRules || '# (none migrated yet)'}
# Not yet migrated (still served by the old blog, so leave the old blog files in place):
${pending || '#   (none)'}
${pending ? '' : '# All known articles migrated: send any other old /blogs/ URL to the Insights listing\nRewriteRule ^blogs/.+$ /insights/ [R=301,L]'}

# 4) One canonical form per URL: trailing slash on page URLs
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]{2,5}$
RewriteCond %{REQUEST_URI} !^/(api|blogs|downloads)/
RewriteRule ^(.*[^/])$ /$1/ [R=301,L]

# 5) Keep gated PDFs out of search results; cache static assets
<IfModule mod_headers.c>
  <FilesMatch "\\.pdf$">
    Header set X-Robots-Tag "noindex, nofollow"
  </FilesMatch>
</IfModule>
<IfModule mod_mime.c>
  AddType image/svg+xml .svg
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml application/json
</IfModule>
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType application/pdf "access plus 7 days"
</IfModule>
`;
fs.writeFileSync(path.join(process.cwd(), 'public', '.htaccess'), tpl);
console.log(`.htaccess generated: ${posts.filter((p) => p.migrated && p.legacy).length} blog redirects, ${posts.filter((p) => !p.migrated).length} pending`);
